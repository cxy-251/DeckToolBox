using DeckToolBox.App.Framework.Models;

namespace DeckToolBox.App.Content.Modules.Essentials;

public static class ChecksumCryptoData
{
    public static ModuleDefinition Create() => new()
    {
        Id = "checksum-crypto",
        Title = "校验与加密：sha256sum、gpg、openssl",
        Keywords = "sha256sum · gpg -c · openssl rand",
        Level = ModuleLevel.Basic,
        Overview = "下载的文件有没有损坏或被篡改？想把一个文件加密后放到网盘？需要一个随机密码？这三件事用系统自带的 sha256sum、gpg 和 openssl 都能完成。",

        Why =
        [
            "1. 校验和 (checksum)：",
            "• 对文件内容计算出一个固定长度的「指纹」，内容改动哪怕一个字节，指纹也完全不同。",
            "• 软件发布页常附带 SHA-256 值。下载后自己计算一遍并对比，一致才说明文件完整、未被替换。",
            "• 只防损坏和替换，不证明发布者身份；要验证发布者，需要检查 GPG 签名（`.sig`/`.asc` 文件）。",
            "2. 对称加密 `gpg -c`：用一个口令加密文件，生成 `.gpg` 文件；解密时输入同一个口令。适合加密备份、上传网盘前的私密文件。口令丢失就无法解密。",
            "3. `openssl rand`：从系统的密码学安全随机数源生成随机数据，可用来生成密码或密钥。",
            "4. `b2sum` 也是系统自带的校验工具（BLAKE2 算法），速度比 sha256sum 更快，适合校验大量文件的备份。",
        ],

        Consequences =
        [
            "• 计算校验和是只读操作。",
            "• `gpg -c` 生成新的加密文件，**不会删除原文件**；确认加密文件可以正常解密后，再自行删除原文件。",
            "• 第一次运行 gpg 会创建 `~/.gnupg` 目录，属于正常现象。",
            "• 口令不要写进命令行参数（会留在命令历史中），让 gpg 弹窗或提示输入。",
        ],

        Steps =
        [
            Step.Read(
                "计算文件的 SHA-256",
                "sha256sum <文件>",
                "把输出与发布页上的值逐字对比，完全一致才说明文件完好。").Then("输出一行：64 个十六进制字符的哈希值，两个空格，然后是文件名。大文件需要几秒到几十秒。"),
            Step.Read(
                "按发布页提供的校验文件批量校验",
                "sha256sum -c <校验文件>",
                "`<校验文件>` 替换为发布页下载的哈希清单（如 `SHA256SUMS`）；每行格式为「哈希值  文件名」，需在待校验文件目录执行。").Then("每个文件一行 `文件名: 成功`；不一致的显示 `失败`，最后提示有几个校验和不匹配；缺失的文件会报错。"),
            Step.Change(
                "为一个目录生成校验清单（用于日后检查备份是否完好）",
                "cd <目录> && find . -type f ! -name SHA256SUMS -exec sha256sum {} + > SHA256SUMS",
                "`<目录>` 替换为要建立清单的目录。`! -name SHA256SUMS` 排除清单自身；`{} +` 把多个文件一次交给 sha256sum。日后在同一目录执行 `sha256sum -c --quiet SHA256SUMS`，只列出不一致的文件。").Then("没有输出，目录中生成 `SHA256SUMS` 文件，每行是一个文件的哈希与相对路径。文件多时需要一些时间。"),
            Step.Change(
                "用口令加密一个文件",
                "gpg -c <文件>",
                "`<文件>` 换成要加密的文件。`-c` 表示只用口令加密（对称加密，默认 AES-256），不需要先生成密钥对；第一次运行会创建 `~/.gnupg` 目录。").Then("弹出口令输入框（或在终端提示），输入两次相同的口令后，同目录下出现 `<文件>.gpg`（内容为乱码）。原文件保持不变。"),
            Step.Change(
                "解密",
                "gpg -o <输出文件> -d <文件>.gpg",
                "`<输出文件>` 指定解密后的明文文件名（避免与输入重名），`<文件>.gpg` 为待解密文件；`-d` 解密。").Then("提示输入口令（最近输入过时可能直接使用缓存），然后生成 `<输出文件>`，内容与加密前相同，并显示使用的加密算法信息。口令错误会提示 `解密失败`。"),
            Step.Read(
                "生成一个随机密码",
                "openssl rand -base64 18",
                "18 字节随机数据经 Base64 编码后为 24 个字符。").Then("输出一行 24 个字符的随机字符串，如 `2Rr+Cbv9njINZwscMLkR1Za0`，每次执行都不同。"),
        ],

        Verify =
        [
            "1. 对同一文件计算两次 `sha256sum`，结果相同；修改文件中任意一个字符后再计算，结果完全不同。",
            "2. 解密出的文件与原文件的 `sha256sum` 一致。",
        ],
    };
}
